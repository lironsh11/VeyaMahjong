# Prepares a Godot-exported iOS Xcode project for CocoaPods and localized Info.plist strings.
# Run by prepare_xcode_project.sh (uses the xcodeproj gem that ships with CocoaPods).
#
#   ruby prepare_xcode_project.rb <export_dir> <repo_root>
#
# 1. Prefixes $(inherited) to the app target's build settings that CocoaPods appends to (Godot
#    sets OTHER_LDFLAGS etc. directly, which would otherwise hide the Pods' libraries).
# 2. Adds <lang>.lproj/InfoPlist.strings (localized NSUserTrackingUsageDescription) from
#    native/levelplay/ios/InfoPlist as a localized resource. Godot itself only writes
#    InfoPlist.strings when the project uses Godot translations, which this game does not; if it
#    ever does, our lines are appended to Godot's files instead.
# 3. Shares a scheme for the app target so `xcodebuild -scheme` works from the command line.
# 4. Writes the Podfile.

require 'fileutils'
require 'xcodeproj'

export_dir = File.expand_path(ARGV[0] || abort('usage: prepare_xcode_project.rb <export_dir> <repo_root>'))
repo_root = File.expand_path(ARGV[1] || abort('usage: prepare_xcode_project.rb <export_dir> <repo_root>'))

proj_path = Dir[File.join(export_dir, '*.xcodeproj')].first || abort("No .xcodeproj in #{export_dir}")
project = Xcodeproj::Project.open(proj_path)
target = project.native_targets.find { |t| t.product_type == 'com.apple.product-type.application' } ||
         abort('No application target in the exported project')
puts "[prepare] project #{File.basename(proj_path)}, target #{target.name}"

# --- 1. $(inherited) ------------------------------------------------------------------------
INHERITED_KEYS = %w[
  OTHER_LDFLAGS FRAMEWORK_SEARCH_PATHS LIBRARY_SEARCH_PATHS HEADER_SEARCH_PATHS
  GCC_PREPROCESSOR_DEFINITIONS OTHER_SWIFT_FLAGS LD_RUNPATH_SEARCH_PATHS OTHER_CFLAGS
  SWIFT_INCLUDE_PATHS
].freeze

target.build_configurations.each do |config|
  INHERITED_KEYS.each do |key|
    value = config.build_settings[key]
    next if value.nil?
    if value.is_a?(Array)
      config.build_settings[key] = ['$(inherited)'] + value unless value.include?('$(inherited)')
    elsif !value.to_s.include?('$(inherited)')
      config.build_settings[key] = "$(inherited) #{value}"
    end
  end
end

# --- 2. localized InfoPlist.strings ---------------------------------------------------------
strings_root = File.join(repo_root, 'native/levelplay/ios/InfoPlist')
languages = Dir[File.join(strings_root, '*.lproj')].map { |d| File.basename(d, '.lproj') }.sort

variant = project.main_group.recursive_children.find do |c|
  c.isa == 'PBXVariantGroup' && c.display_name == 'InfoPlist.strings'
end
if variant.nil?
  variant = project.main_group.new_variant_group('InfoPlist.strings')
  target.resources_build_phase.add_file_reference(variant, true)
end
variant_dir = variant.real_path.dirname

languages.each do |lang|
  source = File.join(strings_root, "#{lang}.lproj", 'InfoPlist.strings')
  relative = "#{lang}.lproj/InfoPlist.strings"
  dest = File.join(variant_dir, relative)
  FileUtils.mkdir_p(File.dirname(dest))
  ours = File.read(source, encoding: 'UTF-8')
  if File.exist?(dest)
    existing = File.read(dest, encoding: 'UTF-8')
    File.write(dest, "#{existing.rstrip}\n#{ours}") unless existing.include?('NSUserTrackingUsageDescription')
  else
    File.write(dest, ours)
  end
  unless variant.children.any? { |f| f.path == relative }
    ref = variant.new_reference(relative)
    ref.name = lang
  end
end
project.root_object.known_regions = (project.root_object.known_regions + languages + ['Base']).uniq
puts "[prepare] InfoPlist.strings for #{languages.join(', ')}"

project.save

# --- 3. shared scheme -----------------------------------------------------------------------
scheme_path = File.join(Xcodeproj::XCScheme.shared_data_dir(proj_path), "#{target.name}.xcscheme")
unless File.exist?(scheme_path)
  scheme = Xcodeproj::XCScheme.new
  scheme.configure_with_targets(target, nil, launch_target: true)
  scheme.save_as(proj_path, target.name, true)
  puts "[prepare] shared scheme #{target.name}"
end

# --- 4. Podfile -----------------------------------------------------------------------------
podfile = <<~RUBY
  # Generated by native/levelplay/ios/scripts/prepare_xcode_project.rb - do not edit by hand.
  platform :ios, '15.0'
  project '#{File.basename(proj_path)}'
  install! 'cocoapods', :warn_for_unused_master_specs_repo => false

  target '#{target.name}' do
    # LevelPlay (IronSourceSDK 9.x) + ATT bridge for the LevelPlayBanner plugin.
    pod 'LiShiLevelPlay', :path => '#{File.join(repo_root, 'native/levelplay/ios/pod')}'
    # Meta Audience Network as a LevelPlay bidder (pulls FBAudienceNetwork; iOS 15+).
    pod 'IronSourceFacebookAdapter', '~> 5.5'
    # StoreKit 2 bridge for the LiShiStoreKit plugin.
    pod 'LiShiStoreKit', :path => '#{File.join(repo_root, 'native/storekit/ios/pod')}'
  end

  post_install do |installer|
    installer.pods_project.targets.each do |t|
      t.build_configurations.each do |c|
        c.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '15.0'
      end
    end
  end
RUBY
File.write(File.join(export_dir, 'Podfile'), podfile)
puts '[prepare] Podfile written'
